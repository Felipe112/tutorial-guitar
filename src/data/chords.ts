export function chordById(id: string): ChordShape | undefined {
  return chords.find((c) => c.id === id) ?? chordAlternatives.find((c) => c.id === id);
}

/** Id de la alternativa sin cejilla de un acorde, si existe. */
export function alternativeIdFor(originalId: string): string | undefined {
  return chordAlternatives.find((c) => c.alternativeTo === originalId)?.id;
}

export const openChords = chords.filter((c) => c.difficulty === "abierto");
export const barreChords = chords.filter((c) => c.difficulty === "cejilla");
