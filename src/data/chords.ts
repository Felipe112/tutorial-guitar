export interface ChordPosition {
  string: number; // 0 = 6ta (grave) .. 5 = 1ra (aguda)
  fret: number | null; // null = cuerda apagada (X), 0 = al aire (O)
  finger: number | null; // 1=índice, 2=medio, 3=anular, 4=meñique, null si no aplica
}

export interface BarreSpan {
  fret: number;
  fromString: number;
  toString: number;
  finger: number;
}

export interface ChordShape {
  id: string;
  name: string;
  shortName: string;
  type: "mayor" | "menor";
  difficulty: "abierto" | "cejilla";
  baseFret: number; // primer traste mostrado en el diagrama (1 = incluye la cejuela)
  positions: ChordPosition[]; // siempre 6 posiciones, una por cuerda, en traste ABSOLUTO
  barreSpans?: BarreSpan[]; // cejillas: un dedo pisando varias cuerdas en el mismo traste
  alternativeTo?: string; // id del acorde con cejilla del que esta es la versión fácil
  tip: string;
}

